#!/bin/zsh
# Запускает ОДИН процесс вывода модели и отказывается стартовать, если другой уже идёт.
#
# Зачем: модель Higgs занимает ~11 ГБ при 16 ГБ на машине. Два процесса вывода
# одновременно не падают с ошибкой — они встают в подкачку и молотят страницы,
# при этом оба выглядят живыми. Так мы однажды загнали подкачку в 27.9 ГБ из 28
# и потеряли час: загрузка дошла до 257 при почти простаивающем процессоре.
# Проверка дешевле, чем разбор последствий.
#
# Использование: scripts/run_one_inference.sh <файл-журнала> <команда...>
set -e
cd "${0:a:h}/.."

LOG="$1"; shift
if [ -z "$LOG" ] || [ $# -eq 0 ]; then
  echo "использование: $0 <файл-журнала> <команда...>" >&2
  exit 2
fi

RUNNING=$(pgrep -f 'src/audiobook.py|src/tts_test.py' | grep -v "^$$\$" || true)
if [ -n "$RUNNING" ]; then
  echo "ОТКАЗ: процесс вывода уже идёт (pid: $(echo $RUNNING | tr '\n' ' '))." >&2
  echo "Модель занимает ~11 ГБ при 16 ГБ всего — второй процесс уведёт машину в подкачку." >&2
  exit 3
fi

SWAP_FREE=$(sysctl -n vm.swapusage | sed -E 's/.*free = ([0-9.]+)M.*/\1/')
echo "перед запуском: свободно подкачки ${SWAP_FREE}M, $(uptime | sed 's/.*load/load/')"

"$@" >> "$LOG" 2>&1
code=$?
echo "код завершения: $code" | tee -a "$LOG"
exit $code
